"""RQ2 table: accuracy without skills and with one skill injected, by the skill's label under each label source.

Every trial counts on its own: a cell is the summed reward over all its trials divided by the number of trials
(3 per task for the baseline, 3 per task-skill pair otherwise), over all annotated tasks. Skills are grouped by
their final human grade (G0-G3, labels/human/human_labels.py), their LLM judge grade (J0-J3, gpt-oss-120b; the
7 pairs it gave no rating are left out of those columns) and whether they are a reference skill. Pairs never run
(reference skills no pool retriever returned) are left out.

Writes to figures/output/rq2/:

    table_grade_accuracy.tex   tab:grade-accuracy   Base, annotator 0-3, LLM judge 0-3, non-reference and reference
                                                    across the top; one row per model under each benchmark

    python3 figures/scripts/generate_grade_accuracy.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = REPO_ROOT / "figures" / "output" / "rq2"
OUT_DIR.mkdir(parents=True, exist_ok=True)
UTILITY_DIR = REPO_ROOT / "labels" / "utility"
JUDGE_DIR = REPO_ROOT / "labels" / "llm_judge" / "gpt-oss-120b"

sys.path.insert(0, str(REPO_ROOT / "labels" / "human"))
from human_labels import load_labels  # noqa: E402

sys.path.insert(0, str(Path(__file__).parent))
from tex_table import TABLE_TAIL, table_head  # noqa: E402

BENCHMARKS = {"SRA-Bench": "sra_bench", "Skill-Usage": "skill_usage"}
MODELS = {"Llama-3.1-8B-Instruct": "Llama-3.1-8B", "GLM-4.5-Air-FP8": "GLM-4.5-Air",
          "Qwen3.6-27B-FP8": "Qwen3.6-27B"}  # weakest first
# column -> header; groups of columns share a spanning header (None: no group)
COLUMNS = {"base": "Base",
           **{("annotator", g): str(g) for g in range(4)},
           **{("judge", g): str(g) for g in range(4)},
           ("reference", False): "Non.", ("reference", True): "Ref."}
GROUPS = [(None, 1), ("Annotator", 4), ("LLM judge", 4), ("Reference", 2)]


def judge_grades() -> dict[tuple[str, str], int]:
    grades = {}
    for path in JUDGE_DIR.glob("*.jsonl"):
        for line in path.read_text().splitlines():
            if line.strip():
                j = json.loads(line)
                if j.get("rating") is not None:
                    grades[(j["instance_id"], j["skill_id"])] = j["rating"]
    return grades


def accuracy(folder: str, model: str, human: dict, judge: dict) -> dict | None:
    """column -> [summed reward, trials] for one benchmark and model; None if the model wasn't run."""
    model_dir = UTILITY_DIR / folder / model
    if not model_dir.is_dir():
        return None
    totals = {c: [0.0, 0] for c in COLUMNS}

    def add(column, rewards):
        totals[column][0] += sum(rewards)
        totals[column][1] += len(rewards)

    for path in sorted(model_dir.glob("*-utility.json")):
        for r in json.loads(path.read_text())["results"]:
            add("base", r["baseline"]["rewards"])
            for c in r["candidates"]:
                if c["rewards"] is None:
                    continue
                pair = (r["instance_id"], c["skill_id"])
                add(("annotator", human[pair]), c["rewards"])
                if pair in judge:
                    add(("judge", judge[pair]), c["rewards"])
                add(("reference", c["is_reference"]), c["rewards"])
    return totals


def main() -> None:
    human = {(r["instance_id"], r["skill_id"]): r["final"] for r in load_labels()}
    judge = judge_grades()
    n = 1 + len(COLUMNS)
    lines = []
    for b_i, (bench, folder) in enumerate(BENCHMARKS.items()):
        if b_i:
            lines.append(r"\midrule")
        lines.append(rf"\multicolumn{{{n}}}{{@{{}}l}}{{\textit{{{bench}}}}} \\")
        for model, short in MODELS.items():
            totals = accuracy(folder, model, human, judge)
            if totals is None:  # model not run on this benchmark
                continue
            print(f"{bench:12} {short:13} " + "  ".join(
                f"{COLUMNS[c] if c == 'base' or c[0] == 'reference' else c[0][0].upper() + COLUMNS[c]} "
                f"{100 * s / k:4.1f} ({k})" for c, (s, k) in totals.items()))
            cells = [f"{100 * s / k:.0f}" if k else "--" for s, k in totals.values()]
            lines.append(rf"\quad {short} & " + " & ".join(cells) + r" \\")

    group_cells, group_rules, start = [], [], 2
    for name, width in GROUPS:
        group_cells.append(rf"\multicolumn{{{width}}}{{c}}{{{name}}}" if name else "")
        if name:
            group_rules.append(rf"\cmidrule({'lr' if start + width - 1 < n else 'l'}){{{start}-{start + width - 1}}}")
        start += width
    (OUT_DIR / "table_grade_accuracy.tex").write_text("\n".join([
        "% Generated by figures/scripts/generate_grade_accuracy.py -- needs \\usepackage{booktabs}",
        *table_head("tab:grade-accuracy"),
        r"\small", r"\setlength{\tabcolsep}{4pt}",
        rf"\begin{{tabular}}{{@{{}}l {'r' * len(COLUMNS)}@{{}}}}", r"\toprule",
        " & " + " & ".join(group_cells) + r" \\",
        " ".join(group_rules),
        "Model & " + " & ".join(COLUMNS.values()) + r" \\",
        r"\midrule", *lines, r"\bottomrule", r"\end{tabular}", TABLE_TAIL,
    ]) + "\n")
    print(f"Saved: {OUT_DIR / 'table_grade_accuracy'}.tex")


if __name__ == "__main__":
    main()
