"""LLM judges vs the human annotators on the annotated subset.

Reads each judge's grades (labels/llm_judge/<model>/<dataset>.jsonl) and the human
labels (labels/human/: first-round grades and the final label), over the
same 2,275 task-skill pairs, and writes one booktabs table per judge to
figures/output/ (\\input them in Overleaf; needs \\usepackage{booktabs}):

    table_judge_grades_dataset_<judge>.tex    tab:judge-grades-dataset-<judge>
        share (and count) of pairs at each grade 0-3 for each annotator
        (first round), the final label and the judge, per dataset.

and two tables with every judge together:

    table_agreement_panel.tex                 tab:agreement-panel
        the judge as a fourth annotator: ordinal alpha over the three humans'
        first-round grades, then over the humans plus each judge (rows), per
        SRA-Bench dataset, SRA-Bench (all) and Skill-Usage (columns).
    table_mean_grades.tex                     tab:mean-grades
        mean grade (0-3) given by each annotator (first round), the final
        label and each judge: a summary of how lenient each rater is.

    python3 figures/scripts/generate_judge_tables.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = REPO_ROOT / "figures" / "output"  # everything the paper includes
OUT_DIR.mkdir(exist_ok=True)
# judge name (used in file names and labels) -> results folder
JUDGES = {
    "gpt-oss-120b": REPO_ROOT / "labels" / "llm_judge" / "gpt-oss-120b",
}

sys.path.insert(0, str(REPO_ROOT / "labels" / "human"))
from generate_rq1_figures import ordinal_alpha  # noqa: E402  (Krippendorff's alpha, ordinal)
from human_labels import ANNOTATORS, load_labels  # noqa: E402  (human grades, labels/human/)
sys.path.insert(0, str(Path(__file__).parent))
from tex_table import TABLE_TAIL, table_head  # noqa: E402

SHORT = {"annotator_1": "A1", "annotator_2": "A2", "annotator_3": "A3"}
SRA = ["bigcodebench", "champ", "logicbench", "medcalcbench", "theoremqa"]
DISPLAY = {
    "bigcodebench": "BigCodeBench", "champ": "CHAMP", "logicbench": "LogicBench",
    "medcalcbench": "MedCalcBench", "theoremqa": "TheoremQA", "skill_usage": "Skill-Usage",
}
BENCHMARKS = {"SRA-Bench": SRA, "Skill-Usage": ["skill_usage"]}


# ── Data ────────────────────────────────────────────────────────────────────

def load_judge(judge_dir: Path, ds: str) -> list[dict]:
    """A judge's records for one dataset, one per task-skill pair. A pair whose first call failed (no rating)
    and was retried appears twice; keep the rated record."""
    records: dict[tuple[str, str], dict] = {}
    for line in (judge_dir / f"{ds}.jsonl").read_text().splitlines():
        j = json.loads(line)
        key = (j["instance_id"], j["skill_id"])
        if key not in records or records[key].get("rating") is None:
            records[key] = j
    return list(records.values())


def load_pairs(judge_dir: Path) -> list[dict]:
    """One dict per task-skill pair: dataset, the three first-round grades, the final label and the judge's grade."""
    human = {(r["instance_id"], r["skill_id"]): r for r in load_labels()}
    pairs = []
    for ds in [*SRA, "skill_usage"]:
        for j in load_judge(judge_dir, ds):
            h = human[(j["instance_id"], j["skill_id"])]
            pairs.append({"dataset": ds, "instance_id": j["instance_id"], "skill_id": j["skill_id"],
                          "humans": [h[a] for a in ANNOTATORS], "final": h["final"], "judge": j["rating"]})
    missing = sum(p["judge"] is None for p in pairs)
    if missing:
        print(f"  [warn] {missing} pairs have no judge rating -- left out")
    return [p for p in pairs if p["judge"] is not None]


def dataset_groups(pairs: list[dict]) -> list[tuple[str, str, list[dict]]]:
    """(LaTeX label, name, pairs) for each SRA-Bench dataset, SRA-Bench (all) and Skill-Usage -- never pooled."""
    groups = [(rf"\quad {DISPLAY[ds]}", DISPLAY[ds], [p for p in pairs if p["dataset"] == ds]) for ds in SRA]
    groups += [(r"\quad \textit{All}", "SRA-Bench (all)", [p for p in pairs if p["dataset"] in SRA]),
               (r"\textit{Skill-Usage}", "Skill-Usage", [p for p in pairs if p["dataset"] == "skill_usage"])]
    return groups


def write(name: str, label: str, colspec: str, header: list[str], rows: list[str],
          tabcolsep: str = "6pt", needs: str = "booktabs") -> None:
    lines = [
        f"% Generated by figures/scripts/generate_judge_tables.py -- needs \\usepackage{{{needs}}}",
        *table_head(label), r"\small", rf"\setlength{{\tabcolsep}}{{{tabcolsep}}}", rf"\begin{{tabular}}{{{colspec}}}",
        r"\toprule", *header, r"\midrule", *rows, r"\bottomrule", r"\end{tabular}", TABLE_TAIL,
    ]
    (OUT_DIR / f"{name}.tex").write_text("\n".join(lines) + "\n")
    print(f"Saved: {OUT_DIR / name}.tex")


# ── Table: grade distribution (tab:judge-grades-dataset-<judge>) ───────────

def table_grades(pairs: list[dict], judge: str) -> None:
    raters = [*((SHORT[a], lambda p, i=i: p["humans"][i]) for i, a in enumerate(ANNOTATORS)),
              ("Final", lambda p: p["final"]), ("Judge", lambda p: p["judge"])]
    rows = [r"\multicolumn{7}{@{}l}{\textit{SRA-Bench}} \\"]
    for g_i, (latex_label, name, P) in enumerate(dataset_groups(pairs)):
        if name == "Skill-Usage":
            rows.append(r"\midrule")
        elif g_i:
            rows.append(r"\cmidrule(l){2-7}")

        def cell(c: int, n: int = len(P)) -> str:  # percentage first, count after it in smaller type
            return f"{100 * c / n:.0f}\\,{{\\scriptsize({c:,})}}"

        for i, (rater, grade) in enumerate(raters):
            counts = [sum(grade(p) == g for p in P) for g in range(4)]
            if rater == "Final":
                rows.append(r"\addlinespace[2pt]")
            first = f"{latex_label} ($n$={len(P):,})" if i == 0 else ""
            rows.append(f"{first} & {rater} & " + " & ".join(cell(c) for c in counts)
                        + f" & {cell(counts[2] + counts[3])} \\\\")
    write(
        f"table_judge_grades_dataset_{judge}", f"tab:judge-grades-dataset-{judge}", "@{}l l r r r r r@{}",
        [r" & & \multicolumn{4}{c}{Grade (\%)} & \\", r"\cmidrule(lr){3-6}",
         r"Dataset & Rater & 0 & 1 & 2 & 3 & $\geq$2 \\"],
        rows,
    )


# ── Table: judge as a fourth annotator (tab:agreement-panel) ─────────────

def table_panel(pairs_by_judge: dict[str, list[dict]]) -> None:
    """3-way alpha over the humans and 4-way alpha with each judge added as a fourth annotator, on the
    first-round grades (before re-annotation)."""
    judges = list(pairs_by_judge)
    first = pairs_by_judge[judges[0]]
    # each judge's grade per (task, skill); judges list pairs in different orders, so match by key
    grade = {j: {(p["instance_id"], p["skill_id"]): p["judge"] for p in P} for j, P in pairs_by_judge.items()}
    for j in judges:
        assert set(grade[j]) == set(grade[judges[0]]), f"{j} does not cover the same task-skill pairs"

    # one row per setup, one column per SRA-Bench dataset, then SRA-Bench (all), then Skill-Usage
    setups = {"Annotators": []} | {("+ LLM judge" if len(judges) == 1 else f"+ {j}"): [] for j in judges}
    for _, _, P in dataset_groups(first):
        setups["Annotators"].append(ordinal_alpha([p["humans"] for p in P]))
        for j, setup in zip(judges, list(setups)[1:]):
            judged = [grade[j][(p["instance_id"], p["skill_id"])] for p in P]
            setups[setup].append(ordinal_alpha([p["humans"] + [g] for p, g in zip(P, judged)]))
    columns = {"bigcodebench": "BigCode", "champ": "CHAMP", "logicbench": "Logic", "medcalcbench": "MedCalc",
               "theoremqa": "TheoremQA"}
    n_sra = len(SRA) + 1  # the datasets and SRA-Bench (all): alpha over all its pairs, not their mean
    write(
        "table_agreement_panel", "tab:agreement-panel", "@{} l " + "c " * (n_sra + 1) + "@{}",
        [rf" & \multicolumn{{{n_sra}}}{{c}}{{SRA-Bench}} & \multirow{{2}}{{*}}{{Skill-Usage}}\\",
         rf"\cmidrule(lr){{2-{n_sra + 1}}}",
         r"\textbf{Setup} & " + " & ".join(columns[ds] for ds in SRA) + r" & \textit{Avg.} &  \\"],
        [f"{setup} & " + " & ".join(f"{x:.2f}" for x in cells) + r" \\" for setup, cells in setups.items()],
        tabcolsep="2pt", needs="booktabs,multirow",
    )


# ── Table: mean grade per rater (tab:mean-grades) ─────────────────────────

def table_mean_grades(pairs_by_judge: dict[str, list[dict]]) -> None:
    """Mean 0-3 grade per rater and dataset. Grades are ordinal, so the mean is a summary of leniency only."""
    judges = list(pairs_by_judge)
    grade = {j: {(p["instance_id"], p["skill_id"]): p["judge"] for p in P} for j, P in pairs_by_judge.items()}

    def mean(xs: list[int]) -> str:
        return f"{sum(xs) / len(xs):.2f}"

    groups = dataset_groups(pairs_by_judge[judges[0]])
    width = max(len(g[0]) for g in groups[:-1])
    n_cols = 1 + len(ANNOTATORS) + 1 + len(judges)
    rows = [rf"\multicolumn{{{n_cols}}}{{@{{}}l}}{{\textit{{SRA-Bench}}}} \\"]
    for latex_label, name, P in groups:
        cells = [mean([p["humans"][i] for p in P]) for i in range(len(ANNOTATORS))]
        cells.append(mean([p["final"] for p in P]))
        cells += [mean([grade[j][(p["instance_id"], p["skill_id"])] for p in P]) for j in judges]
        if name == "SRA-Bench (all)":
            rows.append(r"\addlinespace[2pt]")
        if name == "Skill-Usage":
            rows.append(r"\midrule")
        rows.append(f"{latex_label.ljust(width)} & " + " & ".join(cells) + r" \\")
    write(
        "table_mean_grades", "tab:mean-grades", "@{}l " + "r" * len(ANNOTATORS) + " r " + "r" * len(judges) + "@{}",
        [r" & \multicolumn{" + str(len(ANNOTATORS)) + r"}{c}{Annotators} & & \multicolumn{" + str(len(judges))
         + r"}{c}{LLM judge} \\",
         rf"\cmidrule(lr){{2-{1 + len(ANNOTATORS)}}} \cmidrule(l){{{3 + len(ANNOTATORS)}-{n_cols}}}",
         "Dataset & " + " & ".join(SHORT[a] for a in ANNOTATORS) + " & Final & "
         + " & ".join(judges) + r" \\"],
        rows, tabcolsep="5pt",
    )


def main() -> None:
    pairs_by_judge = {}
    for judge, judge_dir in JUDGES.items():
        pairs = load_pairs(judge_dir)
        print(f"{judge}: {len(pairs)} task-skill pairs")
        table_grades(pairs, judge)
        pairs_by_judge[judge] = pairs
    table_panel(pairs_by_judge)
    table_mean_grades(pairs_by_judge)


if __name__ == "__main__":
    main()
